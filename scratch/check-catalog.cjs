// Regression checks run in an isolated temporary database, never the store database.
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const Module = require('node:module');
const ts = require('typescript');
const root = process.cwd();
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'luc-catalog-'));
const resolve = Module._resolveFilename;
Module._resolveFilename = function(name, ...args) {
  return resolve.call(this, name.startsWith('@/') ? path.join(root, 'src', name.slice(2)) : name, ...args);
};
require.extensions['.ts'] = (module, filename) => module._compile(ts.transpileModule(fs.readFileSync(filename, 'utf8'), { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2022, esModuleInterop: true, jsx: ts.JsxEmit.ReactJSX } }).outputText, filename);
require.extensions[".tsx"] = require.extensions[".ts"];
process.chdir(temporary);
(async () => {
try {
  const { serverDb: db } = require(path.join(root, 'src/lib/serverDb.ts'));
  const { productCategories, videoEmbedUrl, slugify } = require(path.join(root, 'src/lib/catalog.ts'));
  const original = db.getProducts()[0];
  const categories = db.getCategories();
  const primary = categories[0], secondary = categories[1];
  const product = db.createProduct({ ...original, slug: 'catalog-test', categorySlug: primary.slug, categorySlugs: [primary.slug, secondary.slug], specs: { Material: 'Steel', Size: '20 cm' }, seo: { title: 'Custom SEO title', description: 'Custom SEO description' }, video: { provider: 'youtube', id: 'dQw4w9WgXcQ' } });
  assert.notEqual(product.id, original.id);
  assert.deepEqual(productCategories(product), [primary.slug, secondary.slug]);
  assert.equal(product.seo.title, 'Custom SEO title');
  assert.equal(product.specs.Size, '20 cm');
  assert.match(videoEmbedUrl(product.video), /youtube-nocookie/);
  const draft = { ...product, name: 'New Title', slug: slugify('New Title') };
  assert.equal(db.resolveCatalogSlug('product', product.slug), null, 'editing draft must not create redirect');
  assert.ok(db.getProductBySlug(product.slug), 'draft must not alter saved slug');
  db.updateProduct(product.id, draft);
  assert.equal(db.resolveCatalogSlug('product', 'catalog-test'), 'new-title');
  db.updateProduct(product.id, { slug: 'latest-title' });
  assert.equal(db.resolveCatalogSlug('product', 'catalog-test'), 'latest-title', 'old aliases resolve directly to latest slug');
  assert.equal(db.resolveCatalogSlug('product', 'new-title'), 'latest-title');
  assert.throws(() => db.updateProduct(original.id, { slug: 'catalog-test' }), /already used/);
  assert.equal(db.getProductById(original.id).slug, original.slug, 'conflicting save must not mutate product');
  assert.throws(() => db.updateProduct(product.id, { slug: 'bad-slug', categorySlugs: ['missing-category'] }), /existing categories/);
  assert.equal(db.getProductById(product.id).slug, 'latest-title');
  assert.equal(db.resolveCatalogSlug('product', 'latest-title'), null, 'failed save creates no redirect');
  db.updateProduct(product.id, { slug: 'catalog-test', video: { provider: 'vimeo', id: '123456789' } });
  assert.equal(db.resolveCatalogSlug('product', 'catalog-test'), null, 'reverting slug must not create a loop');
  assert.equal(db.resolveCatalogSlug('product', 'latest-title'), 'catalog-test');
  assert.match(videoEmbedUrl(db.getProductById(product.id).video), /player.vimeo.com/);
  assert.throws(() => db.updateProduct(product.id, { video: { provider: 'youtube', id: '<script>' } }), /YouTube ID/);
  db.updateCategory(secondary.id, { name: 'Renamed Secondary', slug: 'renamed-secondary', seo: { title: 'Category SEO', description: 'Category description', keywords: 'gifts, Pakistan' } });
  assert.ok(productCategories(db.getProductById(product.id)).includes('renamed-secondary'));
  assert.equal(db.getProductById(product.id).categorySlug, primary.slug);
  assert.equal(db.resolveCatalogSlug('category', secondary.slug), 'renamed-secondary');
  assert.equal(db.getCategories().find(item => item.id === secondary.id).seo.title, 'Category SEO');
  db.updateCategory(primary.id, { name: 'Renamed Primary', slug: 'renamed-primary' });
  assert.equal(db.getProductById(product.id).categorySlug, 'renamed-primary');
  assert.equal(db.getProductById(product.id).categoryName, 'Renamed Primary');
  const beforeCollision = JSON.stringify(db.getProducts());
  assert.throws(() => db.updateCategory(primary.id, { slug: 'renamed-secondary' }), /already used/);
  assert.equal(JSON.stringify(db.getProducts()), beforeCollision, 'category collision preserves memberships');
  db.updateCategory(primary.id, { slug: 'primary-latest' });
  assert.equal(db.resolveCatalogSlug('category', primary.slug), 'primary-latest');
  db.updateCategory(primary.id, { slug: primary.slug });
  assert.equal(db.resolveCatalogSlug('category', primary.slug), null);
  assert.equal(db.resolveCatalogSlug('category', 'primary-latest'), primary.slug);
  db.updateProduct(product.id, { specs: {}, video: null, seo: { title: '', description: '' }, inStock: false });
  assert.deepEqual(db.getProductById(product.id).specs, {});
  assert.equal(db.getProductById(product.id).video, null);
  assert.equal(db.getProductById(product.id).inStock, false);
  // Reload the module and database to exercise persistence and repeatable migrations.
  global.__laseruv_db.close(); global.__laseruv_db = undefined;
  delete require.cache[require.resolve(path.join(root, 'src/lib/serverDb.ts'))];
  const reopened = require(path.join(root, 'src/lib/serverDb.ts')).serverDb;
  assert.equal(reopened.getProductById(product.id).slug, 'catalog-test');
  assert.equal(reopened.resolveCatalogSlug('product', 'latest-title'), 'catalog-test');
  assert.equal(reopened.getCategories().find(item => item.id === secondary.id).slug, 'renamed-secondary');
  assert.ok(productCategories(reopened.getProductById(product.id)).includes('renamed-secondary'));
  const load = Module._load;
  Module._load = function(name, ...args) {
    if (name === '@/components/product/ProductDetailView' || name === './ShopView') return function View() {};
    if (name === 'next/headers') return { headers: async () => new Headers({ host: '127.0.0.1:3000' }) };
    return load.call(this, name, ...args);
  };
  reopened.updateProduct(product.id, { specs: { Material: 'Brass' }, seo: { title: 'Saved product title', description: 'Saved product description', keywords: 'engraved pens, custom gifts, ' }, video: { provider: 'youtube', id: 'dQw4w9WgXcQ' } });
  const productPage = require(path.join(root, 'src/app/products/[slug]/page.tsx'));
  const productMeta = await productPage.generateMetadata({ params: Promise.resolve({ slug: 'catalog-test' }) });
  assert.equal(productMeta.title.absolute, 'Saved product title');
  assert.equal(productMeta.description, 'Saved product description');
  assert.deepEqual(productMeta.keywords, ['engraved pens', 'custom gifts']);
  assert.equal(productMeta.alternates.canonical, '/products/catalog-test');
  assert.equal(productMeta.metadataBase.host, '127.0.0.1:3000');
  const detail = await productPage.default({ params: Promise.resolve({ slug: 'catalog-test' }) });
  assert.equal(detail.props.product.specs.Material, 'Brass');
  assert.equal(detail.props.product.video.provider, 'youtube');
  await assert.rejects(productPage.default({ params: Promise.resolve({ slug: 'latest-title' }) }), error => error.digest === 'NEXT_REDIRECT;replace;/products/catalog-test;308;');
  await assert.rejects(productPage.default({ params: Promise.resolve({ slug: 'does-not-exist' }) }), error => error.digest === 'NEXT_HTTP_ERROR_FALLBACK;404');
  const shopPage = require(path.join(root, 'src/app/shop/page.tsx'));
  const categoryMeta = await shopPage.generateMetadata({ searchParams: Promise.resolve({ category: 'renamed-secondary' }) });
  assert.equal(categoryMeta.title.absolute, 'Category SEO');
  assert.equal(categoryMeta.description, 'Category description');
  assert.deepEqual(categoryMeta.keywords, ['gifts', 'Pakistan']);
  assert.equal(categoryMeta.alternates.canonical, '/shop?category=renamed-secondary');
  await assert.rejects(shopPage.default({ searchParams: Promise.resolve({ category: secondary.slug, q: 'gift pen' }) }), error => error.digest === 'NEXT_REDIRECT;replace;/shop?category=renamed-secondary&q=gift+pen;308;');
  Module._load = load;
  console.log('PASS: catalog persistence, SEO, specifications, both video providers, multiple categories, atomic failures, redirects, repeated renames, slug reversions, page metadata and 308/404 routing.');
} finally {
  global.__laseruv_db?.close(); global.__laseruv_db = undefined;
  process.chdir(root);
  assert.equal(path.dirname(path.resolve(temporary)), path.resolve(os.tmpdir()));
  assert.ok(path.basename(temporary).startsWith("luc-catalog-"));
  fs.rmSync(temporary, { recursive: true, force: true });
}

})().catch(error => { console.error(error); process.exitCode = 1; });
